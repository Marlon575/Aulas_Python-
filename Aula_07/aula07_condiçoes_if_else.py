# Aula 07 - Condiçoes com if e else
# ==: comparacao.
numero = int(input("Digite um numero:"))
if numero % 2 == 0: # IF-(SE), o resto da divisao de 'numero' por 2, for 0.
 print("O numero e par") # Caso o rsto da divisao por 2 for 0. O programa vai dizer que o numero e par.
else: # Caso contrario
 print("O numero e impar") # Caso contrario imprima impar