# O return é o que faz a função devolver o resultado
# EX: voce coloca algo dendro de uma máquina, ela faz um cálculo, e te devolve o resultado.
# EX Real:
# Voce coloca 10 meticais
# A máquina calcula
# Ela devolve o troco
# O troco é o return


def mostrar_número():
    return 5 # Sempre que alguém chamar, devolve o número  5
resultado = mostrar_número() # Chama a função mostrar_número / a função devolve com 5 / o 5 e guardado em resultado
print(resultado)


